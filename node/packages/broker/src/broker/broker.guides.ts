/**
 * Identifier of one guide page. Also the last URI segment of the matching
 * `broker://guide/<topic>` resource, and the value accepted by the
 * `broker_guide` tool's `topic` argument.
 */
export type BrokerGuideTopic = "index" | "publish-provider" | "connect-client" | "host-config" | "deploy" | "troubleshooting";

/** Scheme + path prefix shared by every guide resource URI. */
export const BROKER_GUIDE_URI_PREFIX = "broker://guide/";

/** RFC 6570 URI template covering every guide page. */
export const BROKER_GUIDE_URI_TEMPLATE = "broker://guide/{topic}";

/** One guide page: its identity, its one-line pitch, and its Markdown body. */
export interface IBrokerGuide {
    /** Stable topic id, used by the tool argument and the resource URI. */
    topic: BrokerGuideTopic;

    /** Canonical resource URI, `broker://guide/<topic>`. */
    uri: string;

    /** Short human title, e.g. "Publish a provider". */
    title: string;

    /** One line describing when to read this page. Shown in the index. */
    summary: string;

    /** The page body, Markdown, self-contained. */
    content: string;
}

