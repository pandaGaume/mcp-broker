/**
 * The broker's self-documentation, as plain Markdown constants.
 *
 * This module is the **source of truth** for how to integrate with an
 * mcp-broker instance. It is served live over MCP by
 * {@link BrokerGuideBehavior} (resources `broker://guide/*` and the
 * `broker_guide` tool), so an agent that can reach the reserved `_broker`
 * slot, or `_all` which aggregates it, learns the integration rules without
 * ever opening a README.
 *
 * Every statement here is derived from the broker's own source, not from the
 * repository's prose documentation. When the two disagree, this file is right
 * and the prose is stale. The markdown docs and the samples import these
 * constants rather than restating them, so there is exactly one copy of the
 * rules to keep correct.
 *
 * Content is written for a machine reader with no prior knowledge of this
 * project: rules are stated as rules, failure modes name their observable
 * signature, and every diagnosis ends in an action.
 */

